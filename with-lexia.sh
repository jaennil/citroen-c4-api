#!/usr/bin/env bash
# Взять Lexia на время одной команды и гарантированно вернуть сбору.
#
# Зачем. Служба c4-telemetry поднимается по udev и занимает устройство сразу при
# подключении. Если полезть к Lexia своим скриптом, не дождавшись, пока служба
# отпустит USB, получается драка за захват: I/O error, потом сброс шины, потом
# устройство вообще пропадает с шины и лечится только переподключением разъёма
# руками. За один вечер это случилось дважды - оба раза потому, что флаг паузы
# ставился и устройство трогалось почти одновременно.
#
# Здесь порядок правильный и его не надо помнить: поставить флаг, ДОЖДАТЬСЯ
# фактического освобождения, выполнить команду, снять флаг на любом выходе.
#
#     ./with-lexia.sh ./.venv/bin/python ecu.py --tx 6A8
#     ./with-lexia.sh ./.venv/bin/python poll_all.py --tx 6A8
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FLAG="$HOME/.config/c4-can/pause"
WAIT="${LEXIA_WAIT:-30}"

[ $# -gt 0 ] || { echo "нечего запускать: ./with-lexia.sh <команда...>"; exit 2; }

mkdir -p "$(dirname "$FLAG")"
cleanup() { rm -f "$FLAG"; }
trap cleanup EXIT INT TERM
touch "$FLAG"

# Ждём, пока служба РЕАЛЬНО отпустит устройство.
#
# Проверяем не журнал и не пробный захват, а факт: держит ли процесс службы
# открытый дескриптор на /dev/bus/usb. Журнал ненадёжен (старая запись совпадает),
# а пробный захват прямо вредит - захват и немедленное освобождение подряд ломают
# устройство, после чего падает уже первая команда рукопожатия.
#
# Ждать надо терпеливо: флаг паузы служба проверяет в начале своего цикла, а во
# время вылазки в чужой блок это до 15 с, плюс инициализация после запуска по udev.
holds_usb() {
  local pid
  pid=$(systemctl show -p MainPID --value c4-telemetry 2>/dev/null)
  [ -n "$pid" ] && [ "$pid" != "0" ] || return 1
  ls -l "/proc/$pid/fd" 2>/dev/null | grep -q "/dev/bus/usb"
}

if holds_usb; then
  echo "служба держит USB, жду освобождения..."
  freed=0
  for _ in $(seq 1 "$WAIT"); do
    holds_usb || { freed=1; break; }
    sleep 1
  done
  if [ "$freed" != 1 ]; then
    echo "сбор не отпустил USB за ${WAIT} с. Останови службу вручную:"
    echo "    sudo systemctl stop c4-telemetry"
    exit 1
  fi
  echo "служба отпустила устройство"
  sleep 2
fi

if ! lsusb -d 103a:f008 >/dev/null 2>&1; then
  echo "устройства нет на шине. Переткни USB-конец, при неудаче сними питание с OBD."
  exit 1
fi

cd "$HERE" || exit 1
"$@"
rc=$?
echo "--- код возврата: $rc ---"
exit $rc
