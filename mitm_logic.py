"""
Логика перехвата кадра подрулевого - отдельно от железа, чтобы её можно было
проверить на ноутбуке.

Зачем так. В машине отлаживать нечем: ошибка в этой логике означает, что на ходу
пропадут поворотники и стеклоочистители, потому что они едут в том же кадре, что
и свет. Поэтому здесь только чистые решения, без CAN и без GPIO: на входе кадр и
события, на выходе - что отдать дальше и в каком положении держать реле. Ровно это
потом переносится в прошивку Teensy один в один.

Четыре правила, которые логика обязана соблюдать:

  1. НЕ ПЕРЕДАВАТЬ, пока реле замкнуто. В замкнутом положении оба трансивера
     сидят на одном сегменте шины, и передача - это столкновение с самим собой.
  2. РЫЧАГ ГЛАВНЕЕ. Любое изменение положения рычага немедленно снимает
     форсирование: физический орган управления не должен оказаться тем, что
     перестало работать.
  3. АВТООТКЛЮЧЕНИЕ ПО ТИШИНЕ. Пока дальний форсирован, нужен пульс от телефона.
     Пропал - возвращаемся в прозрачный режим, иначе ушедший из радиуса телефон
     оставит свет залипшим.
  4. ПРОЗРАЧНОСТЬ ПО УМОЛЧАНИЮ. Нет команды - кадр идёт как есть, реле замкнуто,
     машина электрически стоковая.

Битовая карта кадра НЕ проверена на этой машине: номер бита взят из описания
COM2008P. Поэтому он здесь параметр, а не константа - когда замер на шине покажет
настоящий бит, меняется одно число.
"""

STALK_ID = 0x094          # кадр подрулевого; на этой машине не подтверждён
HIGH_BEAM_BIT = 4         # бит дальнего в байте 0; тоже из описания, не измерен
HEARTBEAT_TIMEOUT = 3.0   # с; дольше молчит телефон - форсирование снимается


class Mitm:
    """Состояние перехватчика. Времена передаются снаружи, часов внутри нет -
    так логику можно проверять без ожиданий в реальном времени."""

    def __init__(self, bit=HIGH_BEAM_BIT, timeout=HEARTBEAT_TIMEOUT):
        self.bit = bit
        self.timeout = timeout
        self.force = False          # просят ли форсировать дальний
        self.last_beat = None       # когда последний раз был пульс
        self.relay_open = False     # разомкнуто ли реле (мы в разрыве)
        self._stalk_bit = None      # что рычаг просил в прошлом кадре

    # --- события снаружи -------------------------------------------------

    def command(self, on: bool, now: float):
        """Команда с телефона: R1 - включить форсирование, R0 - выключить."""
        self.force = bool(on)
        self.last_beat = now if on else None
        self.relay_open = self.force

    def heartbeat(self, now: float):
        """Пульс с телефона. Без него форсирование само отвалится."""
        if self.force:
            self.last_beat = now

    def tick(self, now: float):
        """Проверка тишины. Вызывать регулярно."""
        if self.force and self.last_beat is not None:
            if now - self.last_beat > self.timeout:
                self._drop("пульс пропал")

    # --- обработка кадра -------------------------------------------------

    def on_frame(self, can_id: int, data: bytes, now: float):
        """Что делать с пришедшим кадром.

        Возвращает (кадр_на_выход, передавать_ли). Второе False означает "молчать":
        либо кадр не наш, либо реле замкнуто и передача запрещена правилом 1.
        """
        if can_id != STALK_ID:
            return data, False

        asked = bool(data[0] & (1 << self.bit))
        if self._stalk_bit is None:
            self._stalk_bit = asked
        elif asked != self._stalk_bit:
            # Правило 2: водитель тронул рычаг - форсирование снимается сразу,
            # ещё до того как этот кадр уйдёт дальше.
            self._stalk_bit = asked
            if self.force:
                self._drop("рычаг перебил")

        if not self.relay_open:
            # Правило 1: реле замкнуто, кадр и так дойдёт по проводу. Слушаем молча.
            return data, False

        out = bytearray(data)
        if self.force:
            out[0] |= (1 << self.bit)
        return bytes(out), True

    # --- служебное -------------------------------------------------------

    def _drop(self, why: str):
        self.force = False
        self.last_beat = None
        self.relay_open = False
        self.reason = why

    def state(self):
        return dict(force=self.force, relay_open=self.relay_open,
                    stalk=self._stalk_bit)
