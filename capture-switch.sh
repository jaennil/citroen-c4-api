#!/usr/bin/env bash
# Съёмка переключения между блоками в DiagBox.
#
# Зачем отдельный скрипт: чтобы снять переключение, нужно совпадение трёх условий -
# служба сбора отпустила USB, загружен usbmon, сниффер уже пишет ДО того как Lexia
# попадёт в виртуалку. Порядок важен, а руками он каждый раз путается.
#
# Здесь всё это делается одной командой, а при выходе флаг паузы снимается сам -
# иначе сбор телеметрии остался бы стоять навсегда и это заметилось бы через сутки.
#
#     sudo ./capture-switch.sh [выходной_файл]
#
# Дальше по шагам в DiagBox, с паузами по ~10 с между ними: сегментировать дамп
# я буду по разрывам во времени, других маркеров в потоке USB нет.
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${1:-$HERE/switch.log}"
PAUSE_FLAG="/home/jaennil/.config/c4-can/pause"
OWNER=jaennil

[ "$(id -u)" = 0 ] || { echo "нужен root: sudo $0"; exit 1; }

cleanup() {
  rm -f "$PAUSE_FLAG"
  [ -f "$OUT" ] && chown "$OWNER" "$OUT"
  echo
  echo "флаг паузы снят, сбор телеметрии продолжится сам"
  [ -f "$OUT" ] && echo "дамп: $OUT ($(du -h "$OUT" | cut -f1), $(wc -l < "$OUT") строк)"
}
trap cleanup EXIT

mkdir -p "$(dirname "$PAUSE_FLAG")"
chown "$OWNER" "$(dirname "$PAUSE_FLAG")" 2>/dev/null
touch "$PAUSE_FLAG"
echo "поставил паузу сбору, жду пока отпустит USB..."
# drive.py проверяет флаг раз в 3 с, плюс время на закрытие дескриптора
sleep 6

modprobe usbmon 2>/dev/null || true
[ -e /dev/usbmon0 ] || { echo "нет /dev/usbmon0 - usbmon не загрузился"; exit 1; }

cat <<'STEPS'

=========================================================================
 Пишу. Теперь в DiagBox, НЕ торопясь, с паузой ~10 секунд после каждого шага:

   1. передать Lexia в виртуалку
   2. дойти до списка блоков (выбор авто, базовая проверка - как обычно)
   3. BSI -> открыть измеряемые параметры, посмотреть 10 секунд
   4. выйти назад к списку блоков
   5. Двигатель (Moteur / CMM) -> измеряемые параметры, 10 секунд
   6. выйти назад к списку блоков
   7. снова BSI -> измеряемые параметры, 10 секунд
   8. вернуться сюда и нажать Ctrl+C

 Паузы нужны: по разрывам во времени я разрежу дамп на участки. BSI дважды -
 чтобы отличить настоящее переключение от случайного совпадения.
=========================================================================

STEPS

# Именно без exec: exec заменяет процесс оболочки, вместе с ней пропадает trap,
# и уборка не выполняется - флаг паузы остаётся стоять, а сбор молча висит.
python3 "$HERE/sniff_lexia_full.py" "$OUT"
