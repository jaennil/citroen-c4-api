#!/usr/bin/env bash
# Съёмка своего собственного трафика во время сбора - чтобы сравнить с DiagBox.
#
# Зачем: сбор залипает через ~90 с, и четыре версии причины подряд оказались
# неверными. У нас есть эталон - запись DiagBox с сессией на 235 с без сбоев.
# Нужен свой дамп до момента залипания, тогда сравнение идёт кадр за кадром, а не
# по памяти.
#
# Флаг паузы этот скрипт НЕ ставит и НЕ снимает: снимать его должен тот, кто
# следит за журналом, уже после начала записи. Иначе служба успеет к устройству
# раньше сниффера, и в дампе не будет самого интересного - начала.
#
#     sudo ./capture-collect.sh
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${1:-$HERE/collect.log}"
[ "$(id -u)" = 0 ] || { echo "нужен root: sudo $0"; exit 1; }
modprobe usbmon 2>/dev/null || true
[ -e /dev/usbmon0 ] || { echo "нет /dev/usbmon0"; exit 1; }
trap '[ -f "$OUT" ] && chown jaennil "$OUT"; echo; echo "дамп: $OUT ($(du -h "$OUT" 2>/dev/null | cut -f1))"' EXIT
echo "пишу в $OUT. Теперь скажи мне - я сниму флаг паузы, и сбор пойдёт под запись."
echo "Как в журнале появится залипание, нажми Ctrl+C."
python3 "$HERE/sniff_lexia_full.py" "$OUT"
