def _useful(states):
    """Отсеивает наборы, у которых подпись это само число.

    У части параметров в каталоге вместо текстов состояний лежат номера ("0", "1",
    ... "15"). Подписать ими значение нельзя - получается "0 -> 2", то есть хуже,
    чем не подписывать вовсе.
    """
    if not states:
        return None
    if all(str(v).strip().lstrip("-").isdigit() for v in states.values()):
        return None
    return states


def catalog(name):
    """Состояния из каталога DiagBox для параметра или None.

    Имя бывает голой мнемоникой (так зовутся параметры BSI) и с приставкой блока
    ("V46_32:MP_..."). В каталоге ключ всегда с приставкой, поэтому голое имя ищем
    сначала среди BSI, а уже потом по любому блоку.
    """
    if name.split(":")[-1] in CATALOG_WRONG:
        return None
    st = states_ru.STATES_RU
    if name in st:
        return _useful(st[name])
    if ":" in name:
        return None
    return _useful(st.get(f"BSI2010:{name}") or next(
        (v for k, v in st.items() if k.endswith(":" + name)), None))


def mappings(name):
    """Grafana value mappings для параметра или None.

    Замер поверх каталога: каталог даёт основу, наши подтверждённые подписи её
    перекрывают. Так на панели видны и значения, которых мы ни разу не наблюдали,
    и точная формулировка там, где она проверена.
    """
    if name.startswith("DTC:"):
        m = ENUMS["DTC"]
    else:
        m = dict(catalog(name) or {})
        m.update(ENUMS.get(name) or {})
    if not m:
        return None
    return [{"type": "value",
             "options": {str(k): {"text": v, "index": i} for i, (k, v) in enumerate(sorted(m.items()))}}]
