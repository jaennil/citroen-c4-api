def title(name):
    """Человеческое имя графика. Автоперевод из мнемоники даёт "Температура d eau
    двигатель d", а у панели с границами имя должно читаться."""
    n = NORMS.get(name)
    return n.get("title") if n else None


def steps(name):
    n = NORMS.get(name)
    return n.get("steps") if n else None


def lines(name):
    n = NORMS.get(name)
    return n.get("lines") if n else None


def axis(name):
    n = NORMS.get(name)
    return n.get("axis") if n else None


def help_text(name):
    n = NORMS.get(name)
    if not n:
        return None
    src = {"diagbox": "Источник границ: подсказка каталога DiagBox.",
           "физика": "Источник границ: свойства самой величины, не база DiagBox.",
           "машина": "Источник границ: замеры этой машины."}[n["src"]]
    return f"{n['help']}\n\n{src}"
